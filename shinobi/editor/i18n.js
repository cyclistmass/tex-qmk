    const TABLES = { en, "zh-Hant": zhHant, ja, de, fr, es };
    const LANGUAGES = [
        { id: "en", name: "English" }, { id: "zh-Hant", name: "繁體中文" }, { id: "ja", name: "日本語" },
        { id: "de", name: "Deutsch" }, { id: "fr", name: "Français" }, { id: "es", name: "Español" },
    ];

    // t(key, params): the string in this language, else English; {name} filled from params. t.has(key): whether this
    // language or English has it (for the optional keys).
    function translator(lang) {
        const table = TABLES[lang] || en;
        const t = (key, params) => {
            let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : en[key];
            if (s === undefined) throw new Error(`no string ${key}`);
            if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
            return s;
        };
        t.has = (key) => Object.prototype.hasOwnProperty.call(table, key) || Object.prototype.hasOwnProperty.call(en, key);
        t.lang = TABLES[lang] ? lang : "en";
        return t;
    }

    // The first of the browser's languages the editor has; Chinese only in its Traditional script. Else English.
    function pick(languages) {
        for (const l of languages || []) {
            const x = String(l).toLowerCase();
            if (/^zh-(hant|tw|hk|mo)\b/.test(x)) return "zh-Hant";
            const p = x.split("-")[0];
            if (p !== "zh" && TABLES[p]) return p;
        }
        return "en";
    }

    const api = { translator, pick, languages: LANGUAGES, tables: TABLES };
    root.ShinobiI18n = api;
    if (typeof module !== "undefined" && module.exports) module.exports = api;
